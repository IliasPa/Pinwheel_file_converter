import AppKit
import CryptoKit
import ImageIO
import Observation
import UniformTypeIdentifiers

/// What a copied thing is, for the history's filters.
enum ClipKind: String, Codable, CaseIterable, Sendable {
    case text, link, image, file

    var title: String {
        switch self {
        case .text: "Text"
        case .link: "Links"
        case .image: "Images"
        case .file: "Files"
        }
    }

    var symbolName: String {
        switch self {
        case .text: "text.alignleft"
        case .link: "link"
        case .image: "photo"
        case .file: "doc"
        }
    }
}

/// One copy, as it was on the clipboard.
struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    var id = UUID()
    /// When it was copied (or last copied again from the history).
    var date: Date
    var kind: ClipKind
    /// What the list shows: the text, the link, the file names, the picture's size.
    var preview: String
    /// The app it was copied in.
    var appID: String?
    var appName: String?
    var isFavorite = false
    /// The clipboard's items (several when several files were copied) and
    /// the types each was offered in; the data is kept in files beside the list.
    var contents: [[String]]
    /// Tells copies of the same thing apart.
    var fingerprint: String
    var byteCount: Int
}

/// Copies put together under a name. Like favorites, they're kept for good.
struct ClipCollection: Codable, Identifiable, Equatable, Sendable {
    var id = UUID()
    var name: String
    /// The copies in it, in the order they were added.
    var items: [UUID] = []
}

/// Copies and favorites, kept on this Mac (in Application Support), newest
/// first. Anything an app marks as private (password managers do) is left out.
@Observable
final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    private(set) var collections: [ClipCollection] = []
    /// Copies kept besides the favorites; older ones go.
    var limit = 200 {
        didSet { if limit < oldValue { trim(); save() } }
    }

    @ObservationIgnored let folder: URL
    /// Texts read from disk, kept (a copy never changes).
    @ObservationIgnored private var texts: [UUID: String] = [:]

    init(folder: URL = ClipboardStore.defaultFolder) {
        self.folder = folder
        load()
    }

    static var defaultFolder: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Pinwheel/Clipboard", isDirectory: true)
    }

    // MARK: - Reading the clipboard

    /// Types apps use to say "don't keep this" (passwords, one-time codes).
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    /// Types that can't be put back later (promises of files that are gone by then).
    private static func isKeepable(_ type: String) -> Bool {
        !type.hasPrefix("com.apple.pasteboard.promised") && !type.hasPrefix("com.apple.NSFilePromise")
            && !type.hasPrefix("NSPromise") && type != "com.apple.pasteboard.NSFilePromiseID"
    }

    /// The most kept from one copy; the richest types go first when it's more.
    static let maxBytes = 20_000_000

    /// What's on the clipboard, read in full: each item's types and data.
    /// Nil when it's private or there's nothing that can be kept.
    static func read(_ pasteboard: NSPasteboard) -> [[(type: String, data: Data)]]? {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return nil }
        if pasteboardItems.contains(where: { !Set($0.types.map(\.rawValue)).isDisjoint(with: privateTypes) }) { return nil }
        var total = 0
        var result: [[(type: String, data: Data)]] = []
        for item in pasteboardItems {
            var kept: [(type: String, data: Data)] = []
            for type in item.types.map(\.rawValue) where isKeepable(type) {
                guard let data = item.data(forType: NSPasteboard.PasteboardType(type)) else { continue }
                // The first type of an item is always kept; the rest while there's room.
                if !kept.isEmpty && total + data.count > maxBytes { continue }
                kept.append((type, data))
                total += data.count
            }
            if !kept.isEmpty { result.append(kept) }
        }
        return result.isEmpty ? nil : result
    }

    /// What kind of thing it is, what the list shows, and a fingerprint.
    static func describe(_ contents: [[(type: String, data: Data)]]) -> (kind: ClipKind, preview: String, fingerprint: String)? {
        func data(_ type: UTType, in item: [(type: String, data: Data)]) -> Data? {
            item.first { $0.type == type.identifier }?.data
        }
        func digest(_ parts: [Data]) -> String {
            var hash = SHA256()
            for part in parts { hash.update(data: part) }
            return hash.finalize().map { String(format: "%02x", $0) }.joined()
        }
        let first = contents[0]
        // Files (one item each).
        let files = contents.compactMap { item in
            data(.fileURL, in: item).flatMap { URL(dataRepresentation: $0, relativeTo: nil) }
        }
        if !files.isEmpty {
            let names = files.map(\.lastPathComponent)
            let preview = names.count <= 3 ? names.joined(separator: ", ") : names.prefix(3).joined(separator: ", ") + " and \(names.count - 3) more"
            return (.file, preview, "file:" + digest(files.map { Data($0.path.utf8) }))
        }
        let text = data(.utf8PlainText, in: first).flatMap { String(data: $0, encoding: .utf8) }
            ?? data(.rtf, in: first).flatMap { NSAttributedString(rtf: $0, documentAttributes: nil)?.string }
        // A picture (with no text alongside: text copied from a web page
        // may come with a picture of itself).
        let imageTypes: [UTType] = [.png, .tiff, .jpeg, .heic]
        if text == nil || text?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == true,
           let picture = imageTypes.lazy.compactMap({ data($0, in: first) }).first {
            var size = ""
            if let source = CGImageSourceCreateWithData(picture as CFData, nil),
               let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
               let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int {
                size = " \(width) × \(height)"
            }
            return (.image, "Image" + size, "image:" + digest([picture]))
        }
        if let text {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            let kind: ClipKind = isLink(trimmed) ? .link : .text
            return (kind, String(trimmed.prefix(2000)), "text:" + digest([Data(text.utf8)]))
        }
        if let link = data(.url, in: first).flatMap({ URL(dataRepresentation: $0, relativeTo: nil) }) {
            return (.link, link.absoluteString, "text:" + digest([Data(link.absoluteString.utf8)]))
        }
        return nil
    }

    /// One web (or mail) address and nothing else.
    static func isLink(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https", "mailto", "ftp"].contains(scheme) && (scheme == "mailto" || url.host() != nil)
    }

    // MARK: - Changes

    /// Keeps what was copied. Copying the same thing again moves it to the
    /// top instead. Returns the item, or nil when there was nothing to keep.
    @discardableResult
    func add(_ contents: [[(type: String, data: Data)]], appID: String?, appName: String?, date: Date = Date()) -> ClipItem? {
        guard let (kind, preview, fingerprint) = Self.describe(contents) else { return nil }
        if let index = items.firstIndex(where: { $0.fingerprint == fingerprint }) {
            var again = items.remove(at: index)
            again.date = date
            again.appID = appID ?? again.appID
            again.appName = appName ?? again.appName
            items.insert(again, at: 0)
            save()
            return again
        }
        let item = ClipItem(
            date: date, kind: kind, preview: preview, appID: appID, appName: appName,
            contents: contents.map { $0.map(\.type) }, fingerprint: fingerprint,
            byteCount: contents.flatMap { $0 }.reduce(0) { $0 + $1.data.count }
        )
        do {
            let place = folder(of: item)
            try FileManager.default.createDirectory(at: place, withIntermediateDirectories: true)
            for (itemIndex, representations) in contents.enumerated() {
                for (typeIndex, representation) in representations.enumerated() {
                    try representation.data.write(to: place.appendingPathComponent("\(itemIndex)-\(typeIndex)"))
                }
            }
            if kind == .image, let picture = contents[0].first(where: { UTType($0.type)?.conforms(to: .image) == true })?.data {
                Self.writeThumbnail(of: picture, to: place.appendingPathComponent("thumbnail.png"))
            }
        } catch {
            try? FileManager.default.removeItem(at: folder(of: item))
            return nil
        }
        items.insert(item, at: 0)
        trim()
        save()
        return item
    }

    func toggleFavorite(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isFavorite.toggle()
        save()
        // Taken off the favorites, it counts toward the limit again.
        trim()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        try? FileManager.default.removeItem(at: folder(of: item))
        save()
        if collections.contains(where: { $0.items.contains(item.id) }) {
            for index in collections.indices { collections[index].items.removeAll { $0 == item.id } }
            saveCollections()
        }
    }

    /// Everything but the favorites and what's in collections.
    func clear() {
        let kept = keptForGood
        for item in items where !kept.contains(item.id) { try? FileManager.default.removeItem(at: folder(of: item)) }
        items.removeAll { !kept.contains($0.id) }
        save()
    }

    // MARK: - Collections

    @discardableResult
    func addCollection(named name: String) -> ClipCollection? {
        let name = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !name.isEmpty else { return nil }
        let collection = ClipCollection(name: name)
        collections.append(collection)
        saveCollections()
        return collection
    }

    func rename(_ collection: ClipCollection.ID, to name: String) {
        let name = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !name.isEmpty, let index = collections.firstIndex(where: { $0.id == collection }) else { return }
        collections[index].name = name
        saveCollections()
    }

    /// The collection goes; its copies stay in the history, now counted
    /// toward its limit like any other.
    func removeCollection(_ collection: ClipCollection.ID) {
        collections.removeAll { $0.id == collection }
        saveCollections()
        trim()
        save()
    }

    func add(_ item: ClipItem, to collection: ClipCollection.ID) {
        guard let index = collections.firstIndex(where: { $0.id == collection }), !collections[index].items.contains(item.id) else { return }
        collections[index].items.append(item.id)
        saveCollections()
    }

    func remove(_ item: ClipItem, from collection: ClipCollection.ID) {
        guard let index = collections.firstIndex(where: { $0.id == collection }) else { return }
        collections[index].items.removeAll { $0 == item.id }
        saveCollections()
        trim()
        save()
    }

    /// The collections a copy is in.
    func collections(of item: ClipItem) -> [ClipCollection] {
        collections.filter { $0.items.contains(item.id) }
    }

    /// Favorites and copies in collections: never removed to make room.
    private var keptForGood: Set<UUID> {
        Set(items.filter(\.isFavorite).map(\.id)).union(collections.flatMap(\.items))
    }

    /// Puts it back on the clipboard exactly as it was copied, and moves it to the top.
    func copy(_ item: ClipItem, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        pasteboard.writeObjects(pasteboardItems(of: item))
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    /// The copy as it was on the clipboard, every type of every item (to
    /// copy it again, or drag it into an app).
    func pasteboardItems(of item: ClipItem) -> [NSPasteboardItem] {
        let place = folder(of: item)
        return item.contents.enumerated().map { itemIndex, types -> NSPasteboardItem in
            let restored = NSPasteboardItem()
            for (typeIndex, type) in types.enumerated() {
                if let data = try? Data(contentsOf: place.appendingPathComponent("\(itemIndex)-\(typeIndex)")) {
                    restored.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
            }
            return restored
        }
    }

    /// The whole picture of an image (the list shows a small one).
    func imageData(of item: ClipItem) -> Data? {
        imageFile(of: item).flatMap { try? Data(contentsOf: $0) }
    }

    /// Where the whole picture of an image is kept.
    func imageFile(of item: ClipItem) -> URL? {
        guard item.kind == .image, let index = item.contents.first?.firstIndex(where: { UTType($0)?.conforms(to: .image) == true }) else {
            return nil
        }
        return folder(of: item).appendingPathComponent("0-\(index)")
    }

    /// The small picture for an image in the list.
    func thumbnail(of item: ClipItem) -> URL? {
        item.kind == .image ? folder(of: item).appendingPathComponent("thumbnail.png") : nil
    }

    /// The files of a copy of files.
    func files(of item: ClipItem) -> [URL] {
        guard item.kind == .file else { return [] }
        return item.contents.enumerated().compactMap { itemIndex, types in
            types.firstIndex(of: UTType.fileURL.identifier)
                .flatMap { try? Data(contentsOf: folder(of: item).appendingPathComponent("\(itemIndex)-\($0)")) }
                .flatMap { URL(dataRepresentation: $0, relativeTo: nil) }
        }
    }

    /// The whole text of a text or link (the preview is shortened); from
    /// the formatted text when there's no plain one.
    func text(of item: ClipItem) -> String? {
        guard item.kind == .text || item.kind == .link, let types = item.contents.first else { return nil }
        if let text = texts[item.id] { return text }
        func data(_ type: UTType) -> Data? {
            types.firstIndex(of: type.identifier).flatMap { try? Data(contentsOf: folder(of: item).appendingPathComponent("0-\($0)")) }
        }
        guard let text = data(.utf8PlainText).flatMap({ String(data: $0, encoding: .utf8) })
                ?? data(.rtf).flatMap({ NSAttributedString(rtf: $0, documentAttributes: nil)?.string }) else { return nil }
        if texts.count > 400 { texts.removeAll() }
        texts[item.id] = text
        return text
    }

    // MARK: - Finding

    /// The items matching the filters, newest first. Words in `search` are
    /// looked for in the text and the app's name.
    func matching(
        search: String = "", kind: ClipKind? = nil, appID: String? = nil, favoritesOnly: Bool = false, collection: ClipCollection.ID? = nil
    ) -> [ClipItem] {
        let words = search.split(separator: " ").map(String.init)
        let inCollection = collection.map { id in Set(collections.first { $0.id == id }?.items ?? []) }
        return items.filter { item in
            if favoritesOnly && !item.isFavorite { return false }
            if let inCollection, !inCollection.contains(item.id) { return false }
            if let kind, item.kind != kind { return false }
            if let appID, item.appID != appID { return false }
            let haystack = item.preview + " " + (item.appName ?? "")
            return words.allSatisfy { haystack.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
    }

    // MARK: - Space

    /// What the kept copies take on disk.
    var totalBytes: Int { items.reduce(0) { $0 + $1.byteCount } }

    /// A copy's usual size: from the history once it has a few, or else a
    /// typical mix (mostly text, now and then a screenshot).
    var typicalBytes: Int {
        items.count >= 10 ? totalBytes / items.count : 120_000
    }

    /// "~24 MB" for this many copies.
    func estimate(copies: Int) -> String {
        "~" + Self.roundedSize(copies * typicalBytes)
    }

    /// "3.2 MB"
    static func size(_ bytes: Int) -> String {
        ByteCountFormatter.string(fromByteCount: Int64(bytes), countStyle: .file)
    }

    /// "3 MB": a whole number, for an estimate.
    static func roundedSize(_ bytes: Int) -> String {
        let units = [(1_000_000_000, "GB"), (1_000_000, "MB"), (1_000, "KB")]
        for (index, (unit, name)) in units.enumerated() where bytes >= unit {
            let amount = Int((Double(bytes) / Double(unit)).rounded())
            // 999.6 KB is 1 MB, not 1000 KB.
            if amount >= 1000, index > 0 { return "1 \(units[index - 1].1)" }
            return "\(amount) \(name)"
        }
        return "\(bytes) bytes"
    }

    /// The apps things were copied in, the most recent first.
    var apps: [(id: String, name: String)] {
        var seen: Set<String> = []
        return items.compactMap { item in
            guard let id = item.appID, seen.insert(id).inserted else { return nil }
            return (id, item.appName ?? id)
        }
    }

    // MARK: - Keeping

    private var indexFile: URL { folder.appendingPathComponent("history.json") }
    private var collectionsFile: URL { folder.appendingPathComponent("collections.json") }

    private func folder(of item: ClipItem) -> URL { folder.appendingPathComponent(item.id.uuidString, isDirectory: true) }

    private func load() {
        if let data = try? Data(contentsOf: collectionsFile), let saved = try? JSONDecoder().decode([ClipCollection].self, from: data) {
            collections = saved
        }
        guard let data = try? Data(contentsOf: indexFile), let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = saved
    }

    private func saveCollections() {
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try JSONEncoder().encode(collections).write(to: collectionsFile, options: .atomic)
        } catch {
            // As with the history: fine for now, gone after a restart.
        }
    }

    private func save() {
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try JSONEncoder().encode(items).write(to: indexFile, options: .atomic)
        } catch {
            // The history works for now; it just won't be there after a restart.
        }
    }

    /// The newest `limit` copies stay, and every favorite and copy in a collection.
    private func trim() {
        let keptForGood = keptForGood
        var kept = 0
        var gone: [ClipItem] = []
        items.removeAll { item in
            guard !keptForGood.contains(item.id) else { return false }
            kept += 1
            if kept > limit {
                gone.append(item)
                return true
            }
            return false
        }
        for item in gone { try? FileManager.default.removeItem(at: folder(of: item)) }
    }

    private static func writeThumbnail(of picture: Data, to url: URL) {
        guard let source = CGImageSourceCreateWithData(picture as CFData, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceCreateThumbnailWithTransform: true,
                  kCGImageSourceThumbnailMaxPixelSize: 160,
              ] as CFDictionary),
              let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil)
        else { return }
        CGImageDestinationAddImage(destination, image, nil)
        CGImageDestinationFinalize(destination)
    }
}
